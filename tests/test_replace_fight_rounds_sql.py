"""replace_fight_rounds: round replacement can no longer leave a fight with nothing.

    cd tests && python -m unittest test_replace_fight_rounds_sql -v

On 2026-10-14 a dropped connection between the scraper's DELETE and INSERT
left fight 7349 with no round rows. These tests prove the replacement
functions are all-or-nothing, refuse the inputs that could empty a fight, and
are callable by service_role only. Throwaway Postgres; skips without initdb.
"""
from __future__ import annotations

import os
import unittest

from test_sql_behaviour import PostgresCase, REPO_ROOT

RPC = os.path.join(REPO_ROOT, "fight_rounds_replace_rpc.sql")
ROLLBACK = os.path.join(REPO_ROOT, "fight_rounds_replace_rpc.rollback.sql")

STATS = ", ".join(f"a_{c} integer, b_{c} integer" for c in (
    "kd", "sig_str_landed", "sig_str_attempted", "total_str_landed", "total_str_attempted",
    "td_landed", "td_attempted", "sub_attempts", "rev", "ctrl_seconds", "head_landed",
    "body_landed", "leg_landed", "distance_landed", "clinch_landed", "ground_landed"))

SCHEMA = f"""
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role bypassrls; end if;
end $$;
create table public.fighters (id bigint primary key);
create table public.fights (id bigint generated by default as identity primary key, ufc_fight_id text unique);
create table public.fight_rounds (
  id bigint generated by default as identity primary key,
  fight_id bigint not null references public.fights(id) on delete cascade,
  round_number integer not null,
  fighter_a_id bigint references public.fighters(id), fighter_b_id bigint references public.fighters(id),
  {STATS},
  unique (fight_id, round_number));
create table public.fights_non_ufc (id bigint primary key, ufc_fight_id text unique);
create table public.fight_rounds_non_ufc (
  id bigint not null primary key,
  fight_id bigint not null references public.fights_non_ufc(id) on delete cascade,
  round_number integer not null,
  fighter_a_id bigint references public.fighters(id), fighter_b_id bigint references public.fighters(id),
  {STATS},
  unique (fight_id, round_number));
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
insert into public.fighters values (1), (2);
insert into public.fights (id, ufc_fight_id) values (7349, 'x7349'), (100, 'x100');
insert into public.fights_non_ufc values (49311, 'dw');
insert into public.fight_rounds (fight_id, round_number, fighter_a_id, fighter_b_id, a_sig_str_landed)
  values (7349, 1, 1, 2, 11), (100, 1, 1, 2, 5), (100, 2, 1, 2, 6);
insert into public.fight_rounds_non_ufc (id, fight_id, round_number, a_sig_str_landed) values (900, 49311, 1, 3);
"""

ROUND = '{"round_number": %d, "fighter_a_id": 1, "fighter_b_id": 2, "a_sig_str_landed": %d}'


def payload(*rows):
    return "'[" + ",".join(ROUND % r for r in rows) + "]'::jsonb"


class TestReplaceFightRounds(PostgresCase):

    def setUp(self):
        self.db = "rounds"
        self.psql(f'drop database if exists "{self.db}"')
        self.psql(f'create database "{self.db}"')
        self.psql(SCHEMA, db=self.db)
        self.psql_file(RPC, db=self.db)

    def q(self, sql):
        return self.psql(sql, db=self.db).splitlines()[-1].strip()

    def rounds(self, fight, table="fight_rounds"):
        return self.q(f"select coalesce(string_agg(round_number||':'||a_sig_str_landed, ',' order by round_number), '') "
                      f"from public.{table} where fight_id = {fight}")

    def test_replaces_all_rounds_in_one_call_and_returns_the_count(self):
        self.assertEqual(self.q(f"set role service_role; select public.replace_fight_rounds(100, {payload((1, 7), (2, 8), (3, 9))})"), "3")
        self.assertEqual(self.rounds(100), "1:7,2:8,3:9")
        self.assertEqual(self.rounds(7349), "1:11", "another fight's rounds changed")

    def test_a_failure_part_way_leaves_the_old_rounds_untouched(self):
        # Round 2 names a fighter that does not exist: the insert fails after the delete ran.
        bad = "'[" + (ROUND % (1, 7)) + ',{"round_number": 2, "fighter_a_id": 999, "a_sig_str_landed": 8}' + "]'::jsonb"
        self.psql(f"set role service_role; select public.replace_fight_rounds(100, {bad})", db=self.db, expect_error=True)
        self.assertEqual(self.rounds(100), "1:5,2:6", "a failed replacement lost or changed rounds")

    def test_refuses_to_empty_a_fight(self):
        for p in ("'[]'::jsonb", "null", "'{}'::jsonb"):
            with self.subTest(payload=p):
                err = self.psql(f"select public.replace_fight_rounds(7349, {p})", db=self.db, expect_error=True)
                self.assertIn("refusing", err)
                self.assertEqual(self.rounds(7349), "1:11")

    def test_refuses_an_unknown_fight(self):
        err = self.psql(f"select public.replace_fight_rounds(424242, {payload((1, 1))})", db=self.db, expect_error=True)
        self.assertIn("not in fights", err)

    def test_refuses_rows_naming_another_fight(self):
        p = "'[{\"round_number\": 1, \"fight_id\": 100, \"a_sig_str_landed\": 1}]'::jsonb"
        err = self.psql(f"select public.replace_fight_rounds(7349, {p})", db=self.db, expect_error=True)
        self.assertIn("different fight", err)
        self.assertEqual(self.rounds(100), "1:5,2:6")
        self.assertEqual(self.rounds(7349), "1:11")

    def test_refuses_duplicate_or_missing_round_numbers(self):
        for p in (payload((1, 1), (1, 2)), "'[{\"a_sig_str_landed\": 1}]'::jsonb"):
            with self.subTest(payload=p):
                err = self.psql(f"select public.replace_fight_rounds(100, {p})", db=self.db, expect_error=True)
                self.assertIn("round numbers", err)
                self.assertEqual(self.rounds(100), "1:5,2:6")

    def test_only_service_role_may_call_it(self):
        for fn in ("replace_fight_rounds(bigint, jsonb)", "replace_fight_rounds_non_ufc(bigint, jsonb)"):
            for role, want in (("anon", "f"), ("authenticated", "f"), ("service_role", "t")):
                with self.subTest(fn=fn, role=role):
                    self.assertEqual(self.q(f"select has_function_privilege('{role}', 'public.{fn}', 'EXECUTE')"), want)
            self.assertEqual(self.q(f"select proconfig::text from pg_proc where oid = 'public.{fn}'::regprocedure"),
                             "{\"search_path=public, pg_temp\"}")
            self.assertEqual(self.q(f"select prosecdef from pg_proc where oid = 'public.{fn}'::regprocedure"), "f")
        self.psql(f"set role anon; select public.replace_fight_rounds(7349, {payload((1, 1))})",
                  db=self.db, expect_error=True)
        self.assertEqual(self.rounds(7349), "1:11")

    def test_the_non_ufc_variant_writes_only_its_own_table(self):
        self.assertEqual(self.q(f"set role service_role; select public.replace_fight_rounds_non_ufc(49311, {payload((1, 4), (2, 5))})"), "2")
        self.assertEqual(self.rounds(49311, "fight_rounds_non_ufc"), "1:4,2:5")
        err = self.psql(f"select public.replace_fight_rounds_non_ufc(7349, {payload((1, 1))})", db=self.db, expect_error=True)
        self.assertIn("not in fights_non_ufc", err)
        self.assertEqual(self.rounds(7349), "1:11")

    def test_rerunnable_and_rollback_drops_only_the_functions(self):
        self.psql_file(RPC, db=self.db)
        self.psql_file(ROLLBACK, db=self.db)
        self.assertEqual(self.q("select count(*) from pg_proc where proname like 'replace_fight_rounds%'"), "0")
        self.assertEqual(self.rounds(100), "1:5,2:6")


if __name__ == "__main__":
    unittest.main()
