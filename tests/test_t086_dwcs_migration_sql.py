"""T-086: the DWCS 10.3 move and its rollback, demonstrated on a throwaway Postgres.

    cd tests && python -m unittest test_t086_dwcs_migration_sql -v

The schema below is production's shape for events / fights / fight_rounds
(identity ids, unique keys, indexes, RLS policies, the broad grants production
gives anon), plus the kinds of tables that reference them: an ON DELETE
CASCADE child (fight_odds), a two-parent CASCADE child (predictions), a
RESTRICT child (win_model_locks) and a no-FK evidence table
(pre_fight_snapshots). The DWCS card uses production's real ids.

What is demonstrated:
  * every column of every moved row survives, by fingerprint;
  * no UFC row anywhere changes;
  * the new tables carry their constraints, foreign keys, indexes, RLS,
    policies and grants because they are written out, not inherited;
  * a non-UFC card cannot re-enter `events`, so its bouts cannot enter `fights`;
  * any reference the migration did not expect aborts it with nothing applied;
  * it refuses to run twice;
  * the rollback restores the original bytes, and migrate/rollback/migrate
    cycles cleanly;
  * the rollback refuses to drop a non-UFC card stored after the migration.

No production database is touched. SKIPS where initdb is unavailable.
"""
from __future__ import annotations

import os
import subprocess
import unittest

from test_sql_behaviour import PostgresCase, REPO_ROOT

MIGRATION = os.path.join(REPO_ROOT, "t086_dwcs_non_ufc.sql")
ROLLBACK = os.path.join(REPO_ROOT, "t086_dwcs_non_ufc.rollback.sql")

# Production interleaves a_/b_ per stat; build it in that order.
STATS = ", ".join(f"a_{c} integer, b_{c} integer" for c in (
    "kd", "sig_str_landed", "sig_str_attempted", "total_str_landed", "total_str_attempted",
    "td_landed", "td_attempted", "sub_attempts", "rev", "ctrl_seconds", "head_landed",
    "body_landed", "leg_landed", "distance_landed", "clinch_landed", "ground_landed"))

SCHEMA = f"""
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role bypassrls; end if;
end $$;
create table public.fighters (id bigint primary key, name text);

create table public.events (
  id bigint generated by default as identity primary key,
  ufc_event_id text not null unique, name text not null, event_date date, location text,
  is_upcoming boolean default false, ufc_url text, updated_at timestamptz default now());
create index events_event_date_idx on public.events (event_date desc);
create index events_is_upcoming_idx on public.events (is_upcoming);

create table public.fights (
  id bigint generated by default as identity primary key,
  ufc_fight_id text not null unique,
  event_id bigint references public.events(id) on delete cascade,
  fighter_a_id bigint references public.fighters(id), fighter_b_id bigint references public.fighters(id),
  fighter_a_name text, fighter_b_name text, winner_id bigint references public.fighters(id),
  method text, method_detail text, end_round integer, end_time text, scheduled_rounds integer default 3,
  weight_class text, is_title_fight boolean default false, is_main_event boolean default false, bonus text,
  {STATS},
  ufc_url text, updated_at timestamptz default now(), bell_at timestamptz, bout_order integer,
  is_active boolean not null default true);
create index fights_event_id_idx on public.fights (event_id);

create table public.fight_rounds (
  id bigint generated by default as identity primary key,
  fight_id bigint not null references public.fights(id) on delete cascade,
  round_number integer not null,
  fighter_a_id bigint references public.fighters(id), fighter_b_id bigint references public.fighters(id),
  {STATS},
  unique (fight_id, round_number));

-- Production's RLS and its broad grants.
alter table public.events enable row level security;
alter table public.fights enable row level security;
alter table public.fight_rounds enable row level security;
create policy cfl_public_read on public.events for select to anon, authenticated using (true);
create policy cfl_public_read on public.fights for select to anon, authenticated using (true);
create policy cfl_public_read on public.fight_rounds for select to anon, authenticated using (true);
grant all on public.events, public.fights, public.fight_rounds to anon, authenticated, service_role;
grant all on all sequences in schema public to service_role;

-- Referencing tables of each kind production has.
create table public.fight_odds (id bigint generated always as identity primary key,
  fight_id bigint references public.fights(id) on delete cascade, american_odds integer);
create table public.predictions (id bigint generated always as identity primary key,
  fight_id bigint references public.fights(id) on delete cascade,
  event_id bigint references public.events(id) on delete cascade);
create table public.win_model_locks (id bigint generated always as identity primary key,
  fight_id bigint references public.fights(id) on delete restrict,
  event_id bigint references public.events(id) on delete restrict);
create table public.pre_fight_snapshots (id bigint generated always as identity primary key, fight_id bigint);
"""

FIGHTERS = [215, 4916, 23033, 23034, 23035, 23036, 23037, 23038, 23039, 23040, 1, 2, 3, 4]
DWCS = [(49307, 23033, 23034, 23034, "Decision - Unanimous", 3),
        (49308, 4916, 215, 215, "Submission", 1),
        (49309, 23035, 23036, 23036, "KO/TKO", 1),
        (49310, 23037, 23038, 23037, "Submission", 2),
        (49311, 23039, 23040, 23040, "KO/TKO", 1)]


def seed_sql() -> str:
    s = ["insert into public.fighters values " + ",".join(f"({i},'F{i}')" for i in FIGHTERS) + ";",
         "insert into public.events (id, ufc_event_id, name, event_date, location, ufc_url, updated_at) values "
         "(10, 'u300', 'UFC 300: Pereira vs. Hill', '2024-04-13', 'Las Vegas', 'http://x/u300', '2024-04-14 00:00+00'),"
         "(4259, '2015c944226ad2df', 'DWCS 10.3', '2026-08-25', 'Las Vegas, Nevada, USA', "
         " 'http://www.ufcstats.com/event-details/2015c944226ad2df', '2026-07-19 00:05:07.5881+00'),"
         "(4368, 'u1017', 'UFC Fight Night: Buckley vs. Malott', '2026-10-17', 'Vancouver', 'http://x/u1017', now());"]
    rows = []
    for i, (fid, a, b, w, m, r) in enumerate(DWCS):
        rows.append(f"({fid}, 'dw{fid}', 4259, {a}, {b}, 'A{a}', 'B{b}', {w}, '{m}', 'det', {r}, '{i}:3{i}', 3, "
                    f"'Lightweight', false, {str(i == 0).lower()}, null, " + ",".join(str(fid % 97 + k) for k in range(32))
                    + f", 'http://x/f{fid}', '2026-08-26 01:02:03+00', null, {i + 1}, true)")
    rows.append("(100, 'u100', 10, 1, 2, 'One', 'Two', 1, 'KO/TKO', 'Punch', 1, '1:00', 5, 'Light Heavyweight', true, true, "
                "null, " + ",".join(str(k) for k in range(32)) + ", 'http://x/f100', now(), null, 1, true)")
    rows.append("(53618, 'u53618', 4368, 3, 23040, 'Julien Leblanc', 'Nick Galanti', null, null, null, null, null, 3, "
                "'Featherweight', false, false, null, " + ",".join("null" for _ in range(32))
                + ", 'http://x/f53618', now(), null, 5, true)")
    s.append("insert into public.fights values " + ",".join(rows) + ";")
    rid, rr = 86132, []
    for fid, a, b, _w, _m, rounds in DWCS:
        for n in range(1, rounds + 1):
            rr.append(f"({rid}, {fid}, {n}, {a}, {b}, " + ",".join(str(rid % 13 + k) for k in range(32)) + ")")
            rid += 1
    rr.append("(500, 100, 1, 1, 2, " + ",".join("1" for _ in range(32)) + ")")
    s.append("insert into public.fight_rounds values " + ",".join(rr) + ";")
    # Production's sequences are far past these ids.
    s.append("select setval(pg_get_serial_sequence('public.fights','id'), 60000);")
    s.append("select setval(pg_get_serial_sequence('public.fight_rounds','id'), 100000);")
    s.append("select setval(pg_get_serial_sequence('public.events','id'), 5000);")
    s.append("insert into public.fight_odds (fight_id, american_odds) values (100, -150), (53618, 120);")
    s.append("insert into public.predictions (fight_id, event_id) values (100, 10);")
    s.append("insert into public.win_model_locks (fight_id, event_id) values (53618, 4368);")
    return "\n".join(s)


FULL_STATE = """
select md5(coalesce((select string_agg(e::text,'|' order by id) from public.events e),'')
        || '#' || coalesce((select string_agg(f::text,'|' order by id) from public.fights f),'')
        || '#' || coalesce((select string_agg(r::text,'|' order by id) from public.fight_rounds r),'')
        || '#' || coalesce((select string_agg(o::text,'|' order by id) from public.fight_odds o),'')
        || '#' || coalesce((select string_agg(p::text,'|' order by id) from public.predictions p),'')
        || '#' || coalesce((select string_agg(w::text,'|' order by id) from public.win_model_locks w),''));
"""
UFC_STATE = """
select md5(coalesce((select string_agg(e::text,'|' order by id) from public.events e where id <> 4259),'')
        || '#' || coalesce((select string_agg(f::text,'|' order by id) from public.fights f where event_id <> 4259),'')
        || '#' || coalesce((select string_agg(r::text,'|' order by id) from public.fight_rounds r
                             where fight_id not between 49307 and 49311),'')
        || '#' || coalesce((select string_agg(o::text,'|' order by id) from public.fight_odds o),'')
        || '#' || coalesce((select string_agg(p::text,'|' order by id) from public.predictions p),'')
        || '#' || coalesce((select string_agg(w::text,'|' order by id) from public.win_model_locks w),''));
"""
DWCS_ROWS = """
select md5(string_agg(f::text,'|' order by id)) from public.{fights} f where id between 49307 and 49311
union all
select md5(string_agg(r::text,'|' order by id)) from public.{rounds} r where fight_id between 49307 and 49311;
"""


class TestT086Migration(PostgresCase):

    def setUp(self):
        self.db = "t086"
        self.psql(f'drop database if exists "{self.db}"')
        self.psql(f'create database "{self.db}"')
        self.psql(SCHEMA, db=self.db)
        self.psql(seed_sql(), db=self.db)

    # -- helpers ------------------------------------------------------------
    def q(self, sql):
        return self.psql(sql, db=self.db)

    def run_file(self, path):
        argv = [os.path.join(self.bin_dir, "psql"), "-h", self.tmp, "-p", "55432", "-U", "pg",
                "-d", self.db, "-v", "ON_ERROR_STOP=1", "-f", path]
        out = subprocess.run(self._as(self.runas, argv), capture_output=True, text=True, timeout=180)
        return out.returncode, out.stderr

    def migrate(self):
        rc, err = self.run_file(MIGRATION)
        self.assertEqual(rc, 0, err)

    def rollback(self):
        rc, err = self.run_file(ROLLBACK)
        self.assertEqual(rc, 0, err)

    def exists(self, name):
        return self.q(f"select to_regclass('public.{name}') is not null") == "t"

    # -- the move -----------------------------------------------------------
    def test_every_column_of_every_moved_row_survives(self):
        before = self.q(DWCS_ROWS.format(fights="fights", rounds="fight_rounds")).splitlines()
        self.migrate()
        after = self.q(DWCS_ROWS.format(fights="fights_non_ufc", rounds="fight_rounds_non_ufc")).splitlines()
        self.assertEqual(after, before)
        self.assertEqual(self.q("select count(*) from public.fights_non_ufc"), "5")
        self.assertEqual(self.q("select count(*) from public.fight_rounds_non_ufc"), "8")
        self.assertEqual(self.q("select id||'|'||name||'|'||event_date||'|'||updated_at||'|'||promotion "
                                "from public.events_non_ufc"),
                         "4259|DWCS 10.3|2026-08-25|2026-07-19 00:05:07.5881+00|DWCS")
        self.assertEqual(self.q("select count(*) from public.fights where id between 49307 and 49311"), "0")
        self.assertEqual(self.q("select count(*) from public.events where id = 4259"), "0")

    def test_no_ufc_row_changes(self):
        before = self.q(UFC_STATE)
        self.migrate()
        self.assertEqual(self.q(UFC_STATE), before)

    def test_galanti_has_no_ufc_fight_after_the_move(self):
        q = ("select count(*) from public.fights f join public.events e on e.id = f.event_id "
             "where 23040 in (f.fighter_a_id, f.fighter_b_id) and f.method is not null")
        self.assertEqual(self.q(q), "1")
        self.migrate()
        self.assertEqual(self.q(q), "0")
        # The upcoming booking itself is untouched.
        self.assertEqual(self.q("select count(*) from public.fights where id = 53618"), "1")

    # -- explicit structure -------------------------------------------------
    def test_constraints_and_foreign_keys_are_explicit(self):
        self.migrate()
        got = self.q("""
          select string_agg(conrelid::regclass::text || ' ' || contype::text || ' ' || pg_get_constraintdef(oid), E'\\n'
                            order by conrelid::regclass::text, contype, pg_get_constraintdef(oid))
            from pg_constraint
           where conrelid in ('public.events_non_ufc'::regclass, 'public.fights_non_ufc'::regclass,
                              'public.fight_rounds_non_ufc'::regclass)""").splitlines()
        want = [
            "events_non_ufc c CHECK ((promotion = ANY (ARRAY['DWCS'::text, 'RTU'::text, 'OTHER'::text])))",
            "events_non_ufc p PRIMARY KEY (id)",
            "events_non_ufc u UNIQUE (ufc_event_id)",
            "fight_rounds_non_ufc f FOREIGN KEY (fight_id) REFERENCES fights_non_ufc(id) ON DELETE CASCADE",
            "fight_rounds_non_ufc f FOREIGN KEY (fighter_a_id) REFERENCES fighters(id)",
            "fight_rounds_non_ufc f FOREIGN KEY (fighter_b_id) REFERENCES fighters(id)",
            "fight_rounds_non_ufc p PRIMARY KEY (id)",
            "fight_rounds_non_ufc u UNIQUE (fight_id, round_number)",
            "fights_non_ufc f FOREIGN KEY (event_id) REFERENCES events_non_ufc(id) ON DELETE RESTRICT",
            "fights_non_ufc f FOREIGN KEY (fighter_a_id) REFERENCES fighters(id)",
            "fights_non_ufc f FOREIGN KEY (fighter_b_id) REFERENCES fighters(id)",
            "fights_non_ufc f FOREIGN KEY (winner_id) REFERENCES fighters(id)",
            "fights_non_ufc p PRIMARY KEY (id)",
            "fights_non_ufc u UNIQUE (ufc_fight_id)",
        ]
        self.assertEqual(got, want)
        # NOT NULL and defaults match the UFC tables column for column.
        diff = self.q("""
          select count(*) from (
            select column_name, data_type, is_nullable, ordinal_position, column_default from information_schema.columns
             where table_schema='public' and table_name='fights' and column_name <> 'id'
            except
            select column_name, data_type, is_nullable, ordinal_position, column_default from information_schema.columns
             where table_schema='public' and table_name='fights_non_ufc' and column_name <> 'id') d""")
        self.assertEqual(diff, "0", "fights_non_ufc columns differ from fights")
        diff = self.q("""
          select count(*) from (
            select column_name, data_type, is_nullable, ordinal_position, column_default from information_schema.columns
             where table_schema='public' and table_name='fight_rounds' and column_name <> 'id'
            except
            select column_name, data_type, is_nullable, ordinal_position, column_default from information_schema.columns
             where table_schema='public' and table_name='fight_rounds_non_ufc' and column_name <> 'id') d""")
        self.assertEqual(diff, "0", "fight_rounds_non_ufc columns differ from fight_rounds")

    def test_indexes_are_explicit(self):
        self.migrate()
        got = set(self.q("select indexname from pg_indexes where schemaname='public' "
                         "and tablename like '%non_ufc'").splitlines())
        for want in ("events_non_ufc_pkey", "events_non_ufc_ufc_event_id_key", "events_non_ufc_event_date_idx",
                     "events_non_ufc_is_upcoming_idx", "fights_non_ufc_pkey", "fights_non_ufc_ufc_fight_id_key",
                     "fights_non_ufc_event_id_idx", "fights_non_ufc_fighter_a_id_idx",
                     "fights_non_ufc_fighter_b_id_idx", "fights_non_ufc_winner_id_idx",
                     "fights_non_ufc_method_idx", "fights_non_ufc_weight_class_idx", "fights_non_ufc_bell_at_idx",
                     "fight_rounds_non_ufc_pkey", "fight_rounds_non_ufc_fight_id_round_number_key",
                     "fight_rounds_non_ufc_fight_id_idx"):
            self.assertIn(want, got)

    def test_rls_policies_and_grants_are_explicit(self):
        self.migrate()
        for t in ("events_non_ufc", "fights_non_ufc", "fight_rounds_non_ufc"):
            self.assertEqual(self.q(f"select relrowsecurity from pg_class where oid='public.{t}'::regclass"), "t")
            self.assertEqual(self.q(f"select string_agg(polcmd::text || ':' || polroles::regrole[]::text, ',') "
                                    f"from pg_policy where polrelid='public.{t}'::regclass"),
                             "r:{anon,authenticated}")
            for role in ("anon", "authenticated"):
                for priv in ("SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER"):
                    want = "t" if priv == "SELECT" else "f"
                    self.assertEqual(self.q(f"select has_table_privilege('{role}', 'public.{t}', '{priv}')"),
                                     want, f"{role} {priv} on {t}")
            for priv in ("SELECT", "INSERT", "UPDATE", "DELETE"):
                self.assertEqual(self.q(f"select has_table_privilege('service_role', 'public.{t}', '{priv}')"), "t")
        self.assertEqual(self.q("set role anon; select count(*) from public.fights_non_ufc").splitlines()[-1], "5")
        self.psql("set role anon; insert into public.events_non_ufc (ufc_event_id, name, promotion) "
                  "values ('x', 'DWCS 10.9', 'DWCS')", db=self.db, expect_error=True)

    # -- the guard ----------------------------------------------------------
    def test_a_non_ufc_card_cannot_reenter_the_ufc_tables(self):
        self.migrate()
        # The old scraper's path: upsert the event, then its bouts.
        err = self.psql("insert into public.events (ufc_event_id, name) values ('2015c944226ad2df', 'DWCS 10.3') "
                        "on conflict (ufc_event_id) do update set name = excluded.name",
                        db=self.db, expect_error=True)
        self.assertIn("events_ufc_name_only", err)
        for name in ("DWCS 10.4", "Dana White's Contender Series 2026: Week 5", "Road to UFC Season 4: Final"):
            self.psql(f"insert into public.events (ufc_event_id, name) values ('n{len(name)}', $${name}$$)",
                      db=self.db, expect_error=True)
        err = self.psql("insert into public.fights (ufc_fight_id, event_id) values ('dw49307', 4259)",
                        db=self.db, expect_error=True)
        self.assertIn("foreign key", err)
        # Real UFC names still go in, including the edge cases.
        for name in ("UFC 330: A vs. B", "UFC Fight Night: Rosas Jr. vs. Barcelos", "Noche UFC 2",
                     "The Ultimate Fighter 32 Finale", "Ortiz vs Shamrock 3: The Final Chapter", "UFC Freedom 250"):
            self.q(f"insert into public.events (ufc_event_id, name) values (md5($${name}$$), $${name}$$)")

    def test_the_new_scraper_path_shares_the_id_space(self):
        self.migrate()
        self.q("set role service_role; insert into public.events_non_ufc (ufc_event_id, name, promotion) "
               "values ('dw104', 'DWCS 10.4', 'DWCS')")
        eid = int(self.q("select id from public.events_non_ufc where ufc_event_id = 'dw104'"))
        self.assertGreater(eid, 5000, "events_non_ufc did not draw from events' sequence")
        self.q(f"set role service_role; insert into public.fights_non_ufc (ufc_fight_id, event_id) values ('dwx', {eid})")
        fid = int(self.q("select id from public.fights_non_ufc where ufc_fight_id = 'dwx'"))
        self.assertGreater(fid, 60000, "fights_non_ufc did not draw from fights' sequence")
        nxt = int(self.q("insert into public.fights (ufc_fight_id) values ('next') returning id").splitlines()[0])
        self.assertGreater(nxt, fid, "the UFC table and its sibling issued the same id")

    # -- refusals -----------------------------------------------------------
    def test_an_unexpected_reference_aborts_with_nothing_applied(self):
        for setup in ("insert into public.fight_odds (fight_id, american_odds) values (49307, 200)",
                      "insert into public.predictions (event_id) values (4259)",
                      "insert into public.pre_fight_snapshots (fight_id) values (49311)",
                      "insert into public.events (ufc_event_id, name) values ('rtu', 'Road to UFC Season 5')"):
            with self.subTest(setup=setup):
                self.setUp()
                self.q(setup)
                before = self.q(FULL_STATE)
                rc, err = self.run_file(MIGRATION)
                self.assertNotEqual(rc, 0, f"migration ran despite: {setup}")
                self.assertIn("T-086", err)
                self.assertEqual(self.q(FULL_STATE), before)
                self.assertFalse(self.exists("fights_non_ufc"))

    def test_it_refuses_to_run_twice(self):
        self.migrate()
        rc, err = self.run_file(MIGRATION)
        self.assertNotEqual(rc, 0)
        self.assertIn("has run before", err)

    # -- rollback -----------------------------------------------------------
    def test_rollback_restores_the_original_bytes_and_cycles(self):
        before = self.q(FULL_STATE)
        self.migrate()
        self.rollback()
        self.assertEqual(self.q(FULL_STATE), before)
        for t in ("events_non_ufc", "fights_non_ufc", "fight_rounds_non_ufc"):
            self.assertFalse(self.exists(t))
        self.assertEqual(self.q("select count(*) from pg_constraint where conname = 'events_ufc_name_only'"), "0")
        # And again: the round trip is repeatable.
        self.migrate()
        self.rollback()
        self.assertEqual(self.q(FULL_STATE), before)

    def test_rollback_refuses_to_drop_a_card_stored_after_the_migration(self):
        self.migrate()
        self.q("insert into public.events_non_ufc (ufc_event_id, name, promotion) values ('dw104', 'DWCS 10.4', 'DWCS')")
        rc, err = self.run_file(ROLLBACK)
        self.assertNotEqual(rc, 0)
        self.assertIn("refusing to drop", err)
        self.assertTrue(self.exists("fights_non_ufc"))
        self.assertEqual(self.q("select count(*) from public.fights_non_ufc"), "5")

    def test_rollback_detects_a_tampered_copy(self):
        self.migrate()
        self.q("update public.fights_non_ufc set method = 'Decision - Split' where id = 49307")
        rc, err = self.run_file(ROLLBACK)
        self.assertNotEqual(rc, 0)
        self.assertIn("differ from the originals", err)
        self.assertEqual(self.q("select count(*) from public.fights where id = 49307"), "0")


